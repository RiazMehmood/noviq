//! Feature 022 — Notice Assist data model (data-model.md).
//!
//! The **universal argument frame** is the only predefined structure; the actual
//! content (allegations + the per-allegation questions to ask the officer) is
//! DERIVED by the local model from the attached document (US2). Everything is
//! `#[serde(default)]` and tolerant of unknown keys so a persisted `state_json`
//! survives forward-compatible additions (same discipline as one_ask).

use serde::{Deserialize, Serialize};

/// Where the flow is in the Analyze → Gather → Ground → Draft → Done machine.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum Phase {
    Analyze,
    /// Retired: the flow no longer interrogates the officer. Kept so a session
    /// persisted by an older build still deserializes (it is re-driven to
    /// `CoWrite` on the next turn).
    Gather,
    Ground,
    Draft,
    /// The officer writes his own reply; each turn is a paragraph we critique
    /// against the grounded provisions.
    CoWrite,
    Done,
}

impl Default for Phase {
    fn default() -> Self {
        Phase::Analyze
    }
}

/// Model's best label for the document — selects the reply template only, never
/// gates extraction.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum DocKind {
    ShowCause,
    Warning,
    ExplanationCall,
    AuditPara,
    Other,
}

impl Default for DocKind {
    fn default() -> Self {
        DocKind::Other
    }
}

/// A slot the officer must answer. Generated by the model per allegation (US2);
/// never predefined.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum SlotStatus {
    Open,
    Filled,
    Gap,
}

impl Default for SlotStatus {
    fn default() -> Self {
        SlotStatus::Open
    }
}

#[derive(Debug, Clone, Default, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct SlotQuestion {
    #[serde(default)]
    pub id: u32,
    #[serde(default)]
    pub question: String,
    #[serde(default)]
    pub answer: Option<String>,
    #[serde(default)]
    pub status: SlotStatus,
}

#[derive(Debug, Clone, Default, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct Allegation {
    #[serde(default)]
    pub id: u32,
    #[serde(default)]
    pub text: String,
    #[serde(default)]
    pub invoked_rule: Option<String>,
    #[serde(default)]
    pub invoked_authority: Option<String>,
    #[serde(default)]
    pub questions: Vec<SlotQuestion>,
}

/// Why a grounding attempt ended the way it did (2026-07-18).
///
/// A bare `found = false` collapsed four very different failures into one
/// message — *"not found in the indexed corpus"* — which is a claim about the
/// CORPUS that the code cannot support: it only ever knew that its own narrow
/// lookup missed. Trace `020ac9ac` told an officer that Rule 4 of the E&D Rules
/// was not indexed while trace `29448bd5` was quoting that very rule.
#[derive(Debug, Clone, Copy, Default, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub enum GroundOutcome {
    /// Grounding has not run for this provision yet (also the deserialize
    /// default for sessions persisted before this field existed).
    #[default]
    NotAttempted,
    /// Quoted verbatim from the statute the notice names.
    Found,
    /// The provision text was located, but the notice's statute reference could
    /// not be matched to an indexed document — so we cannot confirm the quote
    /// comes from the instrument the notice actually relies on.
    InstrumentUnresolved,
    /// The statute resolved, but no chunk in it carried this provision token.
    LookupMissed,
    /// Nothing was in scope to search.
    NotInScope,
}

/// A governing provision retrieved verbatim from the corpus during Ground
/// (Principle XI). A non-`Found` outcome ⇒ the reply flags it, never invents it.
#[derive(Debug, Clone, Default, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct CitedRule {
    #[serde(default)]
    pub invoked_ref: String,
    /// Kept so sessions persisted before `outcome` existed still deserialize.
    /// **Derived** — set only by the constructors below, never assigned directly,
    /// so it cannot drift from `outcome`.
    #[serde(default)]
    pub found: bool,
    #[serde(default)]
    pub outcome: GroundOutcome,
    #[serde(default)]
    pub verbatim: Option<String>,
    #[serde(default)]
    pub citation: Option<crate::services::assistant::CitationOut>,
}

impl CitedRule {
    /// A grounded quote. `instrument_confirmed = false` ⇒ the text was located
    /// but the statute could not be verified (`InstrumentUnresolved`).
    pub fn grounded(
        invoked_ref: &str,
        verbatim: String,
        citation: crate::services::assistant::CitationOut,
        instrument_confirmed: bool,
    ) -> Self {
        Self {
            invoked_ref: invoked_ref.to_string(),
            found: true,
            outcome: if instrument_confirmed {
                GroundOutcome::Found
            } else {
                GroundOutcome::InstrumentUnresolved
            },
            verbatim: Some(verbatim),
            citation: Some(citation),
        }
    }

    /// A failed grounding attempt, carrying WHY.
    pub fn missed(invoked_ref: &str, outcome: GroundOutcome) -> Self {
        Self {
            invoked_ref: invoked_ref.to_string(),
            found: false,
            outcome,
            verbatim: None,
            citation: None,
        }
    }

    /// Is this quotable? True for both `Found` and `InstrumentUnresolved` — the
    /// latter is real corpus text, just from an unconfirmed instrument.
    pub fn is_quotable(&self) -> bool {
        matches!(self.outcome, GroundOutcome::Found | GroundOutcome::InstrumentUnresolved)
            || (self.found && self.outcome == GroundOutcome::NotAttempted)
    }
}

/// The universal argument frame — filled by the model from the document (US2)
/// and by grounding (US4).
#[derive(Debug, Clone, Default, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct Frame {
    #[serde(default)]
    pub document_kind: DocKind,
    #[serde(default)]
    pub kind_confidence: f32,
    #[serde(default)]
    pub allegations: Vec<Allegation>,
    #[serde(default)]
    pub relief_or_explanation_sought: Option<String>,
    #[serde(default)]
    pub forum: Option<String>,
    #[serde(default)]
    pub deadline: Option<String>,
    #[serde(default)]
    pub cited_rule_text: Vec<CitedRule>,
    /// Provisions that **protect the officer** — procedural safeguards (inquiry,
    /// opportunity of hearing), the penalty scale, appeal rights, and any rule
    /// bearing on the conduct alleged. Retrieved from the corpus, verbatim + cited.
    /// This is the support the officer needs while writing his own reply.
    #[serde(default)]
    pub support_rules: Vec<CitedRule>,
    /// Characters of document text the analyser actually saw. A tiny value means
    /// the attached copy was a poor scan (OCR salvaged little), so the reply must
    /// warn instead of pretending the notice was fully read.
    #[serde(default)]
    pub source_chars: usize,
}

impl Frame {
    /// True when the notice names no concrete allegation — either the detail
    /// section was illegible/missing in the attached copy, or the model could only
    /// recover a bare label ("Misconduct"). The officer must NOT be asked to
    /// supply it; we tell them the copy is unreadable instead.
    pub fn allegation_details_missing(&self) -> bool {
        self.allegations.iter().all(|a| a.text.split_whitespace().count() <= 2)
    }

    /// Heuristic: the attached copy yielded too little text to trust.
    pub fn poorly_read(&self) -> bool {
        self.source_chars > 0 && self.source_chars < 900
    }
}

/// Root aggregate persisted as `notice_assist_session.state_json`.
#[derive(Debug, Clone, Default, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct NoticeAssistState {
    #[serde(default = "default_version")]
    pub version: u32,
    #[serde(default)]
    pub phase: Phase,
    #[serde(default)]
    pub frame: Frame,
    /// Cached final reply (for resume / export).
    #[serde(default)]
    pub drafted_reply: Option<String>,
}

fn default_version() -> u32 {
    1
}

impl NoticeAssistState {
    pub fn new() -> Self {
        Self { version: 1, phase: Phase::Analyze, frame: Frame::default(), drafted_reply: None }
    }

    /// The next `Open` question across all allegations, if any.
    pub fn next_open_question(&self) -> Option<(usize, usize)> {
        for (ai, a) in self.frame.allegations.iter().enumerate() {
            for (qi, q) in a.questions.iter().enumerate() {
                if q.status == SlotStatus::Open {
                    return Some((ai, qi));
                }
            }
        }
        None
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn state_roundtrips_and_tolerates_unknown_keys() {
        let s = NoticeAssistState::new();
        let json = serde_json::to_string(&s).unwrap();
        let back: NoticeAssistState = serde_json::from_str(&json).unwrap();
        assert_eq!(back.phase, Phase::Analyze);
        // Forward-compat: an unknown key must not fail the load.
        let with_extra = r#"{"version":1,"phase":"gather","frame":{},"futureField":42}"#;
        let parsed: NoticeAssistState = serde_json::from_str(with_extra).unwrap();
        assert_eq!(parsed.phase, Phase::Gather);
    }

    #[test]
    fn next_open_question_walks_allegations_in_order() {
        let mut s = NoticeAssistState::new();
        s.frame.allegations = vec![
            Allegation {
                id: 1,
                questions: vec![SlotQuestion { id: 1, status: SlotStatus::Filled, ..Default::default() }],
                ..Default::default()
            },
            Allegation {
                id: 2,
                questions: vec![SlotQuestion { id: 2, status: SlotStatus::Open, ..Default::default() }],
                ..Default::default()
            },
        ];
        assert_eq!(s.next_open_question(), Some((1, 0)));
    }
}
